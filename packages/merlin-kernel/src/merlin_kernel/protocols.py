from __future__ import annotations

from collections.abc import AsyncIterator, Mapping, Sequence
from typing import Any, Protocol

from merlin_contracts import (
    AgentProgress,
    AgentSummary,
    AgentTask,
    AppEvent,
    ChatMessage,
    ChildSwarmRequest,
    CompactionRecord,
    ContextProjection,
    Finding,
    LeadDecision,
    MailboxDelivery,
    MailboxDeliveryRequest,
    ReportRequest,
    ReportResult,
    ScheduleProjection,
    SwarmRequest,
    ToolContext,
    ToolResult,
    ToolSpec,
)


class SessionStore(Protocol):
    async def create_session(self, *, model: str | None = None) -> str: ...
    async def list_sessions(self) -> Sequence[Mapping[str, Any]]: ...
    async def session_exists(self, session_id: str) -> bool: ...
    async def load_messages(self, session_id: str) -> Sequence[ChatMessage]: ...
    async def append_message(self, session_id: str, message: ChatMessage) -> None: ...
    async def append_event(self, session_id: str, event: AppEvent) -> None: ...
    async def clear_session(self, session_id: str) -> None: ...
    async def load_context(self, session_id: str, identity: ChatMessage) -> ContextProjection: ...
    async def save_compaction(self, record: CompactionRecord) -> CompactionRecord: ...
    async def branch_session(self, session_id: str, sequence: int) -> str: ...
    async def rewind_session(self, session_id: str, sequence: int) -> None: ...
    async def restore_session(self, session_id: str) -> None: ...


class ReadinessService(Protocol):
    async def doctor(self) -> Mapping[str, Any]: ...
    async def logs(self, *, limit: int = 100) -> Sequence[Mapping[str, Any]]: ...
    async def history(
        self, session_id: str | None, *, limit: int = 100
    ) -> Sequence[Mapping[str, Any]]: ...
    async def resume(self, session_id: str) -> Mapping[str, Any]: ...
    async def export_config(self) -> str: ...
    async def support_bundle(self, output: str, session_id: str | None = None) -> str: ...


class ToolBroker(Protocol):
    def describe(self) -> Sequence[ToolSpec]: ...

    async def invoke(
        self, name: str, context: ToolContext, arguments: Mapping[str, Any]
    ) -> ToolResult: ...


class Settings(Protocol):
    async def setup(self) -> Mapping[str, Any]: ...
    async def get_model(self) -> str | None: ...
    async def set_model(self, model: str) -> None: ...
    async def status(self) -> Mapping[str, Any]: ...
    async def plugins(self) -> Sequence[Mapping[str, Any]]: ...


class PackService(Protocol):
    """Kernel-facing pack operations; pack parsing and persistence live elsewhere."""

    async def list_packs(self) -> Sequence[Mapping[str, Any]]: ...
    async def inspect_pack(self, pack_id: str) -> Mapping[str, Any]: ...
    async def enable_pack(self, pack_id: str) -> Mapping[str, Any] | None: ...
    async def disable_pack(self, pack_id: str) -> Mapping[str, Any] | None: ...
    def run_pack(
        self, pack_id: str | None, session_id: str
    ) -> AsyncIterator[Mapping[str, Any]]: ...


class TargetService(Protocol):
    """Kernel-facing target operations; configuration and secrets stay with the owner."""

    async def list_targets(self) -> Sequence[Mapping[str, Any]]: ...
    async def add_target(self, arguments: Sequence[str]) -> Mapping[str, Any]: ...
    async def select_target(self, target_id: str) -> Mapping[str, Any] | None: ...
    async def remove_target(self, target_id: str) -> Mapping[str, Any] | None: ...


class SkillService(Protocol):
    """Kernel-facing skill operations; discovery and instruction loading live elsewhere."""

    async def list_skills(self, session_id: str) -> Sequence[Mapping[str, Any]]: ...
    async def inspect_skill(self, name: str) -> Mapping[str, Any]: ...
    async def enable(self, session_id: str, name: str) -> Mapping[str, Any] | None: ...
    async def disable(self, session_id: str, name: str) -> Mapping[str, Any] | None: ...
    async def instructions_for(self, session_id: str, user_text: str) -> Sequence[str]: ...


class McpService(Protocol):
    """Kernel-facing MCP operations; configuration and secrets stay with the owner."""

    async def list_servers(self) -> Sequence[Mapping[str, Any]]: ...
    async def add_server(self, arguments: Sequence[str]) -> Mapping[str, Any]: ...
    async def remove_server(self, name: str) -> Mapping[str, Any] | None: ...
    async def check_server(self, name: str) -> Mapping[str, Any]: ...
    async def restart_server(self, name: str) -> Mapping[str, Any]: ...


class PermissionService(Protocol):
    async def get_mode(self) -> str: ...
    async def set_mode(self, mode: str, *, session_id: str) -> str: ...
    async def list_permissions(self, session_id: str) -> Sequence[Mapping[str, object]]: ...
    async def authorize_provider(self, session_id: str, workspace_root: str) -> bool: ...
    async def authorize_target(self, session_id: str, workspace_root: str, target: str) -> bool: ...
    async def disable_server(self, name: str) -> Mapping[str, Any]: ...
    async def admit_server(self, name: str, digest: str) -> Mapping[str, Any]: ...


class AgentService(Protocol):
    """Durable agent orchestration and scheduler projections owned outside the kernel."""

    async def list_agents(self, session_id: str) -> Sequence[AgentSummary]: ...
    async def list_tasks(self, session_id: str) -> Sequence[AgentTask | ScheduleProjection]: ...
    async def list_schedules(self, session_id: str) -> Sequence[ScheduleProjection]: ...
    def start_swarm(self, request: SwarmRequest) -> AsyncIterator[AgentProgress]: ...
    async def stop_swarm(self, session_id: str) -> None: ...
    async def deliver_message(self, request: MailboxDeliveryRequest) -> MailboxDelivery: ...
    async def stop_agent(self, session_id: str, agent_id: str) -> None: ...
    async def cancel_task(self, session_id: str, task_id: str) -> str: ...
    async def request_child(self, request: ChildSwarmRequest) -> ScheduleProjection: ...
    async def issue_directive(self, decision: LeadDecision) -> None: ...


class FindingService(Protocol):
    """Finding lifecycle and report rendering owned outside the kernel."""

    async def list_findings(self, session_id: str) -> Sequence[Finding]: ...
    async def accept_finding(self, session_id: str, finding_id: str) -> Finding: ...
    async def reject_finding(self, session_id: str, finding_id: str) -> Finding: ...
    async def generate_report(self, request: ReportRequest) -> ReportResult: ...
    async def compare_reports(self, older_id: str, newer_id: str) -> Sequence[str]: ...


class MemoryService(Protocol):
    async def list_memory(self, status: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    async def import_file(self, path: str) -> Mapping[str, Any]: ...
    async def export_file(self, path: str) -> Mapping[str, Any]: ...
    async def accept(self, bundle_id: str, record_ids: Sequence[str]) -> Mapping[str, Any]: ...
    async def reject(
        self, bundle_id: str, record_ids: Sequence[str], reason: str
    ) -> Mapping[str, Any]: ...
    async def delete(
        self, bundle_id: str, record_ids: Sequence[str], reason: str
    ) -> Mapping[str, Any]: ...


class BrowserService(Protocol):
    async def list_contexts(self, session_id: str) -> Sequence[Mapping[str, object]]: ...
    async def list_tabs(
        self, session_id: str, context_id: str
    ) -> Sequence[Mapping[str, object]]: ...
    async def takeover(self, session_id: str, context_id: str) -> Mapping[str, object]: ...
    async def cleanup(self, session_id: str, context_id: str) -> Mapping[str, object]: ...
    async def resume(self, session_id: str, context_id: str) -> Mapping[str, object]: ...


class PromotionService(Protocol):
    """Operator-controlled promotion lifecycle owned outside the kernel."""

    async def propose(self, session_id: str, arguments: Sequence[str]) -> Mapping[str, Any]: ...
    async def list_candidates(self) -> Sequence[Mapping[str, Any]]: ...
    async def show_candidate(self, candidate_id: str) -> Mapping[str, Any]: ...
    async def evaluate(
        self, session_id: str, candidate_id: str, suite_id: str | None
    ) -> Mapping[str, Any]: ...
    async def accept(self, candidate_id: str, reason: str) -> Mapping[str, Any]: ...
    async def reject(self, candidate_id: str, reason: str) -> Mapping[str, Any]: ...
    async def activate(self, candidate_id: str) -> Mapping[str, Any]: ...
    async def history(self, kind: str | None) -> Sequence[Mapping[str, Any]]: ...
    async def rollback(self, kind: str) -> Mapping[str, Any]: ...
